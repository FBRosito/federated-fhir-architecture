"""
fhir_benchmark.py
-----------------
FHIR R4 server latency and completeness benchmark.

Metrics:
  - POST latency (bundle upload): P50, P95, P99
  - GET latency (paginated search): P50, P95, P99
  - Completeness score: fraction of expected resources found on the server
  - Throughput: bundles/second for batch loading

Usage:
    uv run python evaluation/fhir_benchmark.py --fhir-url http://localhost:8080/fhir --n-samples 100

Note: run LOCALLY to validate code and tune parameters; publishable numbers
must come from a cloud environment with dedicated infrastructure to eliminate WSL noise.
"""

from __future__ import annotations

import argparse
import logging
import os
import statistics
import time
from dataclasses import dataclass, field
from pathlib import Path

import httpx

log = logging.getLogger(__name__)

_DEFAULT_FHIR_URL = os.getenv("FHIR_SERVER_URL", "http://localhost:8080/fhir")
_REQUEST_TIMEOUT = 60.0


@dataclass
class FHIRBenchmarkResult:
    """FHIR benchmark results."""

    post_latencies_ms: list[float] = field(default_factory=list)
    get_latencies_ms: list[float] = field(default_factory=list)
    completeness_score: float = 0.0
    n_bundles_posted: int = 0
    n_resources_found: int = 0
    n_resources_expected: int = 0
    errors: list[str] = field(default_factory=list)

    def _percentiles(self, latencies: list[float]) -> dict[str, float]:
        if not latencies:
            return {
                "p50": float("nan"),
                "p95": float("nan"),
                "p99": float("nan"),
                "mean": float("nan"),
            }
        s = sorted(latencies)
        n = len(s)
        return {
            "p50": s[int(n * 0.50)],
            "p95": s[int(n * 0.95)],
            "p99": s[min(int(n * 0.99), n - 1)],
            "mean": statistics.mean(latencies),
        }

    def post_stats(self) -> dict[str, float]:
        """Latency percentiles (p50/p95/p99/mean) for POST operations."""
        return self._percentiles(self.post_latencies_ms)

    def get_stats(self) -> dict[str, float]:
        """Latency percentiles (p50/p95/p99/mean) for GET operations."""
        return self._percentiles(self.get_latencies_ms)

    def __str__(self) -> str:
        p = self.post_stats()
        g = self.get_stats()
        return (
            f"FHIR Benchmark Results\n"
            f"  POST (n={len(self.post_latencies_ms)}): "
            f"mean={p['mean']:.1f}ms P50={p['p50']:.1f}ms P95={p['p95']:.1f}ms P99={p['p99']:.1f}ms\n"
            f"  GET  (n={len(self.get_latencies_ms)}): "
            f"mean={g['mean']:.1f}ms P50={g['p50']:.1f}ms P95={g['p95']:.1f}ms P99={g['p99']:.1f}ms\n"
            f"  Completeness: {self.completeness_score:.2%} "
            f"({self.n_resources_found}/{self.n_resources_expected} resources)\n"
            f"  Errors: {len(self.errors)}"
        )


def benchmark_post_bundles(
    fhir_url: str,
    bundles_dir: Path,
    n_samples: int = 50,
) -> FHIRBenchmarkResult:
    """
    Measures POST latency for existing Transaction Bundles in bundles_dir.

    Only reads bundles already generated by mimic_builder — does not generate new data.
    Bundles are sent one at a time (no parallelism) to isolate latency.

    Args:
        fhir_url:    Base URL of the FHIR R4 server.
        bundles_dir: Directory containing bundle_NNNNNN.json files.
        n_samples:   Number of bundles to send.

    Returns:
        FHIRBenchmarkResult with POST latencies.
    """
    result = FHIRBenchmarkResult()
    bundle_files = sorted(bundles_dir.glob("bundle_*.json"))[:n_samples]

    if not bundle_files:
        log.warning("No bundles found in %s.", bundles_dir)
        return result

    log.info("POST benchmark: %d bundles at %s...", len(bundle_files), fhir_url)

    with httpx.Client(timeout=_REQUEST_TIMEOUT) as client:
        for bf in bundle_files:
            payload = bf.read_bytes()
            t0 = time.perf_counter()
            try:
                resp = client.post(
                    f"{fhir_url.rstrip('/')}",
                    content=payload,
                    headers={"Content-Type": "application/fhir+json"},
                )
                elapsed_ms = (time.perf_counter() - t0) * 1000
                if resp.status_code < 400:
                    result.post_latencies_ms.append(elapsed_ms)
                    result.n_bundles_posted += 1
                else:
                    result.errors.append(f"POST {bf.name}: HTTP {resp.status_code}")
            except Exception as exc:
                result.errors.append(f"POST {bf.name}: {exc}")

    log.info(
        "POST benchmark: %d bundles | stats: %s",
        result.n_bundles_posted,
        result.post_stats(),
    )
    return result


def benchmark_get_resources(
    fhir_url: str,
    resource_types: list[str] | None = None,
    n_pages: int = 10,
) -> FHIRBenchmarkResult:
    """
    Measures GET latency for paginated FHIR resource searches.

    Args:
        fhir_url:        Base URL of the FHIR R4 server.
        resource_types:  List of resource types to search (default: Patient, Condition, DocumentReference).
        n_pages:         Number of pages to fetch per type.

    Returns:
        FHIRBenchmarkResult with GET latencies.
    """
    if resource_types is None:
        resource_types = ["Patient", "Condition", "DocumentReference"]

    result = FHIRBenchmarkResult()
    base = fhir_url.rstrip("/")

    with httpx.Client(timeout=_REQUEST_TIMEOUT) as client:
        for rtype in resource_types:
            url: str | None = f"{base}/{rtype}?_count=50"
            page = 0
            while url and page < n_pages:
                t0 = time.perf_counter()
                try:
                    resp = client.get(url, timeout=_REQUEST_TIMEOUT)
                    elapsed_ms = (time.perf_counter() - t0) * 1000
                    if resp.status_code == 200:
                        result.get_latencies_ms.append(elapsed_ms)
                        bundle = resp.json()
                        entries = bundle.get("entry", [])
                        result.n_resources_found += len(entries)
                        url = None
                        for link in bundle.get("link", []):
                            if link.get("relation") == "next":
                                url = link.get("url")
                                break
                    else:
                        result.errors.append(f"GET {rtype}: HTTP {resp.status_code}")
                        break
                except Exception as exc:
                    result.errors.append(f"GET {rtype}: {exc}")
                    break
                page += 1

    log.info(
        "GET benchmark: %d latencies | stats: %s",
        len(result.get_latencies_ms),
        result.get_stats(),
    )
    return result


def benchmark_completeness(
    fhir_url: str,
    bundles_dir: Path,
    n_samples: int = 50,
) -> FHIRBenchmarkResult:
    """
    Checks completeness: fraction of Patient IDs from bundles that exist in FHIR R4.

    A score < 1.0 indicates some bundles were not loaded successfully.

    Args:
        fhir_url:    Base URL of the FHIR R4 server.
        bundles_dir: Directory containing bundle_NNNNNN.json files.
        n_samples:   Number of bundles to verify.

    Returns:
        FHIRBenchmarkResult with completeness_score.
    """
    import json as _json

    result = FHIRBenchmarkResult()
    bundle_files = sorted(bundles_dir.glob("bundle_*.json"))[:n_samples]

    if not bundle_files:
        return result

    result.n_resources_expected = len(bundle_files)
    base = fhir_url.rstrip("/")

    with httpx.Client(timeout=_REQUEST_TIMEOUT) as client:
        for bf in bundle_files:
            try:
                data = _json.loads(bf.read_text(encoding="utf-8"))
                # Extract patient_id from the first Patient entry
                patient_id = None
                for entry in data.get("entry", []):
                    res = entry.get("resource", {})
                    if res.get("resourceType") == "Patient":
                        for ident in res.get("identifier", []):
                            patient_id = ident.get("value")
                            break
                        break

                if not patient_id:
                    continue

                resp = client.get(
                    f"{base}/Patient?identifier={patient_id}",
                    timeout=_REQUEST_TIMEOUT,
                )
                if resp.status_code == 200:
                    found = resp.json().get("total", 0)
                    if found > 0:
                        result.n_resources_found += 1
                    else:
                        result.errors.append(f"Patient {patient_id} not found in FHIR.")
            except Exception as exc:
                result.errors.append(f"{bf.name}: {exc}")

    result.completeness_score = result.n_resources_found / max(
        result.n_resources_expected, 1
    )
    log.info(
        "Completeness: %.2f%% (%d/%d)",
        result.completeness_score * 100,
        result.n_resources_found,
        result.n_resources_expected,
    )
    return result


def run_full_benchmark(
    fhir_url: str = _DEFAULT_FHIR_URL,
    bundles_dir: str = "etl_worker/data/bundles",
    n_samples: int = 50,
) -> dict[str, dict]:
    """
    Runs the full benchmark (POST + GET + completeness) and returns results.

    Returns:
        {"post": {...}, "get": {...}, "completeness": {...}}
    """
    bdir = Path(bundles_dir)
    results = {}

    log.info("=== FHIR Benchmark — %s ===", fhir_url)

    post_result = benchmark_post_bundles(fhir_url, bdir, n_samples=n_samples)
    results["post"] = {
        **post_result.post_stats(),
        "n_bundles": post_result.n_bundles_posted,
        "n_errors": len(post_result.errors),
    }

    get_result = benchmark_get_resources(fhir_url)
    results["get"] = {
        **get_result.get_stats(),
        "n_resources": get_result.n_resources_found,
        "n_errors": len(get_result.errors),
    }

    comp_result = benchmark_completeness(fhir_url, bdir, n_samples=n_samples)
    results["completeness"] = {
        "score": comp_result.completeness_score,
        "n_found": comp_result.n_resources_found,
        "n_expected": comp_result.n_resources_expected,
        "n_errors": len(comp_result.errors),
    }

    log.info("\n%s", post_result)
    return results


def main() -> None:
    """CLI entry point: run the FHIR R4 latency/completeness benchmark."""
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(name)s — %(message)s",
    )
    parser = argparse.ArgumentParser(
        description="FHIR R4 latency and completeness benchmark."
    )
    parser.add_argument("--fhir-url", default=_DEFAULT_FHIR_URL)
    parser.add_argument("--bundles-dir", default="etl_worker/data/bundles")
    parser.add_argument("--n-samples", type=int, default=50)
    args = parser.parse_args()

    results = run_full_benchmark(
        fhir_url=args.fhir_url,
        bundles_dir=args.bundles_dir,
        n_samples=args.n_samples,
    )

    import json

    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
